from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(slots=True)
class BuildingDesignPlan:
    """
    Deterministic design envelope produced from PlanningFacts
    and PlanningConstraints.

    This object is intentionally a design-planning intermediate
    representation.

    It does NOT create architectural objects such as walls,
    rooms, doors, windows, columns, etc.

    Those objects can be generated by a later geometry/layout
    generator using this plan.
    """

    plot_area_m2: float | None = None

    maximum_fsi: float | None = None

    maximum_built_up_area_m2: float | None = None

    maximum_ground_coverage_m2: float | None = None

    front_setback_m: float | None = None

    rear_setback_m: float | None = None

    side_setback_left_m: float | None = None

    side_setback_right_m: float | None = None

    minimum_open_space_m2: float | None = None

    maximum_height_m: float | None = None

    maximum_storeys: int | None = None

    car_parking_required: float | None = None

    two_wheeler_parking_required: float | None = None

    visitor_parking_required: float | None = None

    parking_area_required_m2: float | None = None

    fire_access_required: bool | None = None

    fire_lift_required: bool | None = None

    fire_staircase_required: bool | None = None

    minimum_exit_count: int | None = None

    minimum_exit_width_m: float | None = None

    staircase_count: int | None = None

    staircase_width_m: float | None = None

    corridor_width_m: float | None = None

    lift_required: bool | None = None

    lift_count: int | None = None

    accessible_entrance_required: bool | None = None

    ramp_required: bool | None = None

    ramp_width_m: float | None = None

    ramp_gradient: float | None = None

    recreational_open_space_m2: float | None = None

    amenity_space_m2: float | None = None

    road_widening: bool | None = None

    reservation_present: bool | None = None

    metadata: dict[str, Any] = field(
        default_factory=dict
    )

    def to_dict(self) -> dict[str, Any]:
        """
        Convert the deterministic design plan into a
        serializable dictionary.
        """

        result = {
            "plot_area_m2": self.plot_area_m2,

            "maximum_fsi": self.maximum_fsi,

            "maximum_built_up_area_m2":
                self.maximum_built_up_area_m2,

            "maximum_ground_coverage_m2":
                self.maximum_ground_coverage_m2,

            "front_setback_m":
                self.front_setback_m,

            "rear_setback_m":
                self.rear_setback_m,

            "side_setback_left_m":
                self.side_setback_left_m,

            "side_setback_right_m":
                self.side_setback_right_m,

            "minimum_open_space_m2":
                self.minimum_open_space_m2,

            "maximum_height_m":
                self.maximum_height_m,

            "maximum_storeys":
                self.maximum_storeys,

            "car_parking_required":
                self.car_parking_required,

            "two_wheeler_parking_required":
                self.two_wheeler_parking_required,

            "visitor_parking_required":
                self.visitor_parking_required,

            "parking_area_required_m2":
                self.parking_area_required_m2,

            "fire_access_required":
                self.fire_access_required,

            "fire_lift_required":
                self.fire_lift_required,

            "fire_staircase_required":
                self.fire_staircase_required,

            "minimum_exit_count":
                self.minimum_exit_count,

            "minimum_exit_width_m":
                self.minimum_exit_width_m,

            "staircase_count":
                self.staircase_count,

            "staircase_width_m":
                self.staircase_width_m,

            "corridor_width_m":
                self.corridor_width_m,

            "lift_required":
                self.lift_required,

            "lift_count":
                self.lift_count,

            "accessible_entrance_required":
                self.accessible_entrance_required,

            "ramp_required":
                self.ramp_required,

            "ramp_width_m":
                self.ramp_width_m,

            "ramp_gradient":
                self.ramp_gradient,

            "recreational_open_space_m2":
                self.recreational_open_space_m2,

            "amenity_space_m2":
                self.amenity_space_m2,

            "road_widening":
                self.road_widening,

            "reservation_present":
                self.reservation_present,

            "metadata":
                dict(self.metadata),
        }

        return {
            key: value
            for key, value in result.items()
            if value is not None
        }
